"""Regenerate tables/leaderboard.md and figures/time_vs_subopt_<tier>.png from tables/results.jsonl.

  python -m lassobench.report            (owned by bench-harness)

Task P: one row per (solver, hardware, tol) run, plus per (solver, hardware) the time-to-loose / time-to-tight
(fastest run whose max relative duality gap meets 1e-4 / 1e-6). Because the harness gap uses the simple
rescaled-residual dual point, it can be pessimistic; "subopt" columns use the cached reference objective.
Task CV: one row per run. Dev runs (max_targets set) and tagged 'dev' rows are excluded.
"""
from __future__ import annotations

import math
import os
from collections import defaultdict

from lassobench.runner import REPO, RESULTS, read_results

LB = os.path.join(REPO, "tables", "leaderboard.md")
FIG = os.path.join(REPO, "figures")
TIER_ORDER = ["syn-s", "pca1k", "pca1k-raw", "unit-100k", "unit-800k", "unit-xl", "syn-xl"]
# fixed categorical order (validated reference palette); a solver keeps its color across figures
PALETTE = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948"]


def hw_label(r):
    h = r.get("hardware", {})
    if r.get("config", {}).get("device") == "cuda" or (h.get("gpu_model") and "cpu_" not in r["solver"]):
        return (h.get("gpu_model") or "gpu").replace("NVIDIA ", "")
    cpu = (h.get("cpu_model") or "cpu").replace("Intel(R) Xeon(R) ", "").replace(" CPU", "").split(" @")[0]
    n = r.get("config", {}).get("solver_args", {}).get("n_jobs") or h.get("n_threads")
    return f"{cpu} x{n}"


def f(x, fmt="{:.3g}"):
    if x is None or (isinstance(x, float) and (math.isnan(x))):
        return "-"
    return fmt.format(x)


def keep(r):
    return r.get("max_targets") is None and (r.get("tag") or "") != "dev"


def build(rows=None):
    rows = [r for r in (rows if rows is not None else read_results()) if keep(r)]
    by_tier = defaultdict(list)
    for r in rows:
        by_tier[r["tier"]].append(r)
    tiers = [t for t in TIER_ORDER if t in by_tier] + sorted(t for t in by_tier if t not in TIER_ORDER)
    out = ["# Leaderboard", "", f"Generated by `python -m lassobench.report` from `tables/results.jsonl` "
           f"({len(rows)} rows). Times in seconds, wall clock incl. transfers/precompute, warm-up excluded. "
           "conv = max relative duality gap level (loose <= 1e-4, tight <= 1e-6). "
           "subopt = (P - P_ref)/P_ref vs the cached float64 reference.", ""]
    for t in tiers:
        rs = by_tier[t]
        shape = rs[-1].get("shape", {})
        out += [f"## {t}  (n={shape.get('n_train')}, p={shape.get('p')}, T={shape.get('T')})", ""]
        P = [r for r in rs if r["task"] == "P"]
        if P:
            best = defaultdict(dict)
            for r in P:
                if r.get("status") != "ok" or "metrics" not in r:
                    continue
                k = (r["solver"], hw_label(r))
                m = r["metrics"]
                for lvl, thr in (("loose", 1e-4), ("tight", 1e-6)):
                    if m["gap_rel_max"] <= thr:
                        best[k][lvl] = min(best[k].get(lvl, 1e30), r["time_total_s"])
                    so = m.get("subopt_rel_max")
                    if so is not None and so <= thr:
                        best[k]["so_" + lvl] = min(best[k].get("so_" + lvl, 1e30), r["time_total_s"])
            out += ["**Task P: time to accuracy** (fastest run reaching the level; '-' = never reached)", "",
                    "| solver | hardware | time-to-loose (gap) | time-to-tight (gap) | time-to-loose (subopt) | time-to-tight (subopt) |",
                    "|---|---|---|---|---|---|"]
            for k in sorted({(r["solver"], hw_label(r)) for r in P}):
                b = best.get(k, {})
                out.append(f"| {k[0]} | {k[1]} | {f(b.get('loose'), '{:.1f}')} | {f(b.get('tight'), '{:.1f}')} | "
                           f"{f(b.get('so_loose'), '{:.1f}')} | {f(b.get('so_tight'), '{:.1f}')} |")
            out += ["", "<details><summary>Task P runs</summary>", "",
                    "| solver | hardware | tol | status | time | prepare | conv | gap max | gap med | subopt max | nnz med | peak RAM GB | peak GPU GB |",
                    "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
            for r in sorted(P, key=lambda r: (r["solver"], hw_label(r), -(r["config"].get("tol") or 0))):
                m = r.get("metrics", {})
                out.append(f"| {r['solver']} | {hw_label(r)} | {f(r['config'].get('tol'))} | {r['status']} | "
                           f"{f(r.get('time_total_s'), '{:.1f}')} | {f(r.get('time_prepare_s'), '{:.1f}')} | "
                           f"{m.get('converged_level', '-')} | {f(m.get('gap_rel_max'))} | {f(m.get('gap_rel_median'))} | "
                           f"{f(m.get('subopt_rel_max'))} | {f(m.get('nnz_median'), '{:.0f}')} | "
                           f"{f(r.get('peak_ram_gb'), '{:.1f}')} | {f(r.get('peak_gpu_mem_gb'), '{:.1f}')} |")
            out += ["", "</details>", ""]
        CV = [r for r in rs if r["task"] == "CV"]
        if CV:
            out += ["**Task CV** (5-fold CV over the 50-alpha grid, refit, test R2 on the held-out split)", "",
                    "| solver | hardware | tol | status | time | test R2 mean | median | mean (reliable) | train R2 | nnz med | nnz mean | Jaccard vs ref | tag |",
                    "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
            for r in sorted(CV, key=lambda r: (r["solver"], hw_label(r))):
                m = r.get("metrics", {})
                out.append(f"| {r['solver']} | {hw_label(r)} | {f(r['config'].get('tol'))} | {r['status']} | "
                           f"{f(r.get('time_total_s'), '{:.1f}')} | {f(m.get('r2_test_mean'), '{:.4f}')} | "
                           f"{f(m.get('r2_test_median'), '{:.4f}')} | {f(m.get('r2_test_mean_reliable'), '{:.4f}')} | "
                           f"{f(m.get('r2_train_mean'), '{:.3f}')} | {f(m.get('nnz_median'), '{:.0f}')} | "
                           f"{f(m.get('nnz_mean'), '{:.0f}')} | {f(m.get('jaccard_ref_mean'), '{:.3f}')} | {r.get('tag') or ''} |")
            out.append("")
    os.makedirs(os.path.dirname(LB), exist_ok=True)
    with open(LB, "w") as fh:
        fh.write("\n".join(out) + "\n")
    figs = [plot_tier(t, by_tier[t]) for t in tiers]
    return LB, [p for p in figs if p]


def plot_tier(tier, rs):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    P = [r for r in rs if r["task"] == "P" and r.get("status") == "ok" and "metrics" in r]
    if not P:
        return None
    groups = defaultdict(list)
    for r in P:
        groups[(r["solver"], hw_label(r))].append(r)
    solvers = sorted({k[0] for k in groups})
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), sharex=True)
    for ax, (key, lab) in zip(axes, (("gap_rel_max", "max relative duality gap"),
                                     ("subopt_rel_max", "max relative suboptimality vs reference"))):
        any_pts = False
        for i, (k, g) in enumerate(sorted(groups.items())):
            pts = sorted((r["time_total_s"], r["metrics"].get(key)) for r in g if r["metrics"].get(key) is not None)
            pts = [(x, max(y, 1e-12)) for x, y in pts]
            if not pts:
                continue
            any_pts = True
            c = PALETTE[solvers.index(k[0]) % len(PALETTE)]
            ls = "-" if "cpu" not in k[0] else "--"
            ax.plot(*zip(*pts), ls, marker="o", ms=5, lw=2, color=c, label=f"{k[0]} ({k[1]})")
        for thr, name in ((1e-4, "loose"), (1e-6, "tight")):
            ax.axhline(thr, color="#888", lw=0.8, ls=":")
            ax.text(ax.get_xlim()[0] if any_pts else 1, thr, f" {name}", va="bottom", fontsize=8, color="#555")
        ax.set_xscale("log"); ax.set_yscale("log")
        ax.set_xlabel("wall-clock time (s)"); ax.set_ylabel(lab)
        ax.grid(True, which="major", color="#ddd", lw=0.6)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    axes[0].legend(fontsize=7, frameon=False, loc="best")
    shp = P[-1]["shape"]
    fig.suptitle(f"{tier}: time vs accuracy, Task P (n={shp['n_train']}, p={shp['p']}, T={shp['T']})", fontsize=11)
    fig.tight_layout()
    os.makedirs(FIG, exist_ok=True)
    path = os.path.join(FIG, f"time_vs_subopt_{tier}.png")
    fig.savefig(path, dpi=130)
    plt.close(fig)
    return path


if __name__ == "__main__":
    lb, figs = build()
    print(lb)
    for p in figs:
        print(p)
